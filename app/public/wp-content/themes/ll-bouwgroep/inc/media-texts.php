/**
 * Returns the original English demo title for a filename, or ''.
 *
 * @param string $file Demo filename.
 * @return string
 */
function llb_demo_image_english_title( $file ) {
	$file = (string) $file;
	if ( '' === $file || ! function_exists( 'llb_demo_images' ) ) {
		return '';
	}

	foreach ( llb_demo_images() as $item ) {
		if ( isset( $item['file'] ) && (string) $item['file'] === $file && isset( $item['title'] ) ) {
			return (string) $item['title'];
		}
	}

	return '';
}

/**
 * Applies Dutch media texts to one attachment (keeps manual edits).
 *
 * @param int    $attachment_id Attachment ID.
 * @param string $file          Demo filename key.
 * @return void
 */
function llb_apply_media_text_to_attachment( $attachment_id, $file ) {
	$attachment_id = absint( $attachment_id );
	$file          = (string) $file;
	$texts         = llb_media_texts();

	if ( ! $attachment_id || ! isset( $texts[ $file ] ) ) {
		return;
	}

	$post = get_post( $attachment_id );
	if ( ! ( $post instanceof WP_Post ) || 'attachment' !== $post->post_type ) {
		return;
	}

	$dutch          = $texts[ $file ];
	$english_title  = llb_demo_image_english_title( $file );
	$basename_title = (string) preg_replace( '/\.[^.]+$/', '', $file );
	$update         = array( 'ID' => $attachment_id );
	$dirty          = false;

	$current_title = (string) $post->post_title;
	if (
		( '' !== $english_title && $current_title === $english_title )
		|| $current_title === $basename_title
	) {
		$update['post_title'] = $dutch['title'];
		$dirty                = true;
	}

	if ( '' === trim( (string) $post->post_excerpt ) ) {
		$update['post_excerpt'] = $dutch['caption'];
		$dirty                  = true;
	}

	if ( '' === trim( (string) $post->post_content ) ) {
		$update['post_content'] = $dutch['desc'];
		$dirty                  = true;
	}

	if ( $dirty ) {
		wp_update_post( $update );
	}

	$alt = (string) get_post_meta( $attachment_id, '_wp_attachment_image_alt', true );
	if ( '' === $alt || ( '' !== $english_title && $alt === $english_title ) ) {
		update_post_meta( $attachment_id, '_wp_attachment_image_alt', $dutch['alt'] );
	}
}

/**
 * Applies Dutch texts to all known demo attachments.
 *
 * @return void
 */
function llb_apply_media_texts() {
	if ( ! function_exists( 'llb_find_demo_attachment' ) ) {
		return;
	}

	foreach ( llb_media_texts() as $file => $texts ) {
		unset( $texts );
		$attachment_id = llb_find_demo_attachment( $file );
		if ( ! $attachment_id ) {
			continue;
		}
		llb_apply_media_text_to_attachment( $attachment_id, $file );
	}
}

/**
 * One-time apply of Dutch media texts (after demo import / WebP migration).
 *
 * @return void
 */
function llb_maybe_apply_media_texts() {
	if ( get_option( 'llb_media_texts_v1' ) ) {
		return;
	}

	llb_apply_media_texts();
	update_option( 'llb_media_texts_v1', 1 );
}
add_action( 'admin_init', 'llb_maybe_apply_media_texts', 40 );
